#!/usr/bin/env node

/**
 * Vendor what the CLI needs to know about each API endpoint it calls (API-1081):
 * the chains the endpoint accepts and its top-level request fields.
 *
 *   npm run endpoints:sync    rewrite src/api-endpoints.json from the live spec
 *   npm run endpoints:check   exit 3 if src/api-endpoints.json differs from it
 *
 * The source is the public OpenAPI spec (https://api.nansen.ai/openapi.json).
 * Only endpoints that src/schema.json names are kept. The CLI rejects a chain
 * the endpoint does not accept before it spends a request, and `nansen schema`
 * lists the chains per command. src/__tests__/input-validation.test.js checks
 * that every option a command accepts maps to a field the endpoint has.
 *
 * Pass a file path instead of the URL with --spec <path> (offline use).
 * Exit codes: 0 = in sync / written, 3 = out of sync, 1 = the check failed.
 */

import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

export const SPEC_URL = 'https://api.nansen.ai/openapi.json';
export const OUTPUT_PATH = fileURLToPath(new URL('../src/api-endpoints.json', import.meta.url));
const SCHEMA_PATH = fileURLToPath(new URL('../src/schema.json', import.meta.url));

/** Every `endpoint` named anywhere in src/schema.json. */
export function schemaEndpoints(schema) {
  const endpoints = new Set();
  (function walk(node) {
    if (!node || typeof node !== 'object') return;
    if (typeof node.endpoint === 'string') endpoints.add(node.endpoint);
    for (const value of Object.values(node)) walk(value);
  })(schema.commands);
  return [...endpoints].sort();
}

function resolver(spec) {
  const components = spec.components?.schemas ?? {};
  return function resolve(node) {
    let current = node;
    const seen = new Set();
    while (current && typeof current === 'object' && typeof current.$ref === 'string') {
      if (seen.has(current.$ref)) break;
      seen.add(current.$ref);
      current = components[current.$ref.split('/').pop()];
    }
    return current ?? {};
  };
}

/** Enum values reachable from a property schema (through anyOf/oneOf/allOf and arrays). */
function enumValues(node, resolve, depth = 0) {
  const schema = resolve(node);
  if (depth > 6 || !schema || typeof schema !== 'object') return [];
  const values = [];
  if (Array.isArray(schema.enum)) values.push(...schema.enum.filter(v => typeof v === 'string'));
  if (schema.const && typeof schema.const === 'string') values.push(schema.const);
  for (const key of ['anyOf', 'oneOf', 'allOf']) {
    for (const alt of schema[key] ?? []) values.push(...enumValues(alt, resolve, depth + 1));
  }
  if (schema.items) values.push(...enumValues(schema.items, resolve, depth + 1));
  return values;
}

/** { field, chains, fields } for one endpoint, or null when the spec does not describe it. */
export function describeEndpoint(spec, endpoint) {
  const resolve = resolver(spec);
  const operations = spec.paths?.[endpoint];
  if (!operations) return null;
  const operation = operations.post ?? operations.get;
  if (!operation) return null;
  const bodySchema = operation.requestBody?.content?.['application/json']?.schema;
  if (!bodySchema) {
    const params = (operation.parameters ?? []).map(p => resolve(p)).filter(p => p.in === 'query');
    return { fields: params.map(p => p.name).sort() };
  }
  const body = resolve(bodySchema);
  const properties = body.properties ?? {};
  const result = { fields: Object.keys(properties).sort() };
  for (const field of ['chain', 'chains']) {
    if (!properties[field]) continue;
    const chains = [...new Set(enumValues(properties[field], resolve))].sort();
    if (chains.length) {
      result.chainField = field;
      result.chains = chains;
      break;
    }
  }
  return result;
}

export function buildEndpoints(spec, schema) {
  const endpoints = {};
  for (const endpoint of schemaEndpoints(schema)) {
    const description = describeEndpoint(spec, endpoint);
    if (description) endpoints[endpoint] = description;
  }
  return {
    $comment: 'Generated by scripts/sync-api-endpoints.js from https://api.nansen.ai/openapi.json. Do not edit by hand; run: npm run endpoints:sync',
    endpoints,
  };
}

export function render(data) {
  return JSON.stringify(data, null, 2) + '\n';
}

async function loadSpec(argv) {
  const at = argv.indexOf('--spec');
  if (at !== -1) return JSON.parse(fs.readFileSync(argv[at + 1], 'utf8'));
  const response = await fetch(SPEC_URL, { signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw new Error(`GET ${SPEC_URL} returned HTTP ${response.status}`);
  return response.json();
}

async function main(argv) {
  const check = argv.includes('--check');
  const schema = JSON.parse(fs.readFileSync(SCHEMA_PATH, 'utf8'));
  const expected = render(buildEndpoints(await loadSpec(argv), schema));
  const current = fs.existsSync(OUTPUT_PATH) ? fs.readFileSync(OUTPUT_PATH, 'utf8') : '';
  if (!check) {
    fs.writeFileSync(OUTPUT_PATH, expected);
    console.log(`Wrote ${OUTPUT_PATH}`);
    return 0;
  }
  if (current === expected) {
    console.log('src/api-endpoints.json matches the live API spec.');
    return 0;
  }
  const before = JSON.parse(current || '{"endpoints":{}}').endpoints;
  const after = JSON.parse(expected).endpoints;
  console.log('OUT OF SYNC: src/api-endpoints.json differs from the live API spec. Run: npm run endpoints:sync');
  for (const endpoint of [...new Set([...Object.keys(before), ...Object.keys(after)])].sort()) {
    if (JSON.stringify(before[endpoint]) === JSON.stringify(after[endpoint])) continue;
    const was = new Set(before[endpoint]?.chains ?? []);
    const now = new Set(after[endpoint]?.chains ?? []);
    const added = [...now].filter(c => !was.has(c));
    const removed = [...was].filter(c => !now.has(c));
    console.log(`- ${endpoint}${added.length ? ` +chains: ${added.join(', ')}` : ''}${removed.length ? ` -chains: ${removed.join(', ')}` : ''}`);
  }
  return 3;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).then(code => process.exit(code), err => {
    console.error(err.message);
    process.exit(1);
  });
}
